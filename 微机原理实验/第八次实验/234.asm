START: 
    MOV AX,DATA
    MOV DS,AX
    MOV AH,01H	
    MOV BX,00H ;滚动行数(移向下一字节代表从下一行开始打印)   
RUN:
    MOV DX,OFFSET LEFT
    MOV SI,DX
    ADD SI,BX   ;计算当前行数（本轮从该行开始打印）
    MOV DX,OFFSET RIGHT
    MOV DI,DX
    ADD DI,BX   ;计算当前行数（本轮从该行开始打印）
