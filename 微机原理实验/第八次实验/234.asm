    INC SI;指向下一行
    INC DI    
    PUSH CX
    MOV CX,0500H ;延迟
    LOOP $     
    POP CX 
    LOOP WRITE1
    
    MOV AL,0H
    OUT 0H,AL
    MOV CX,08H 
