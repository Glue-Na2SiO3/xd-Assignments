DATA SEGMENT  
    NUMS:
    DB 08H,18H,28H,08H,08H,08H,08H,3EH ;数字1
    DB 38H,44H,04H,04H,08H,10H,20H,7EH ;数字2    
    DB 18H,24H,04H,18H,18H,04H,24H,18H ;数字3
DATA ENDS
CODE SEGMENT
    ASSUME CS:CODE,DS:DATA
START:
    MOV AX,DATA
    MOV DS,AX
    MOV AH,01H
    MOV BX,00H 
RUN:
    MOV DX,OFFSET NUMS
    MOV SI,DX
    ADD SI,BX
    MOV CX,08H
WAITE:
    MOV AL,0H
    OUT 00H,AL
    MOV AL,[SI]
    OUT 02H,AL
    MOV AL,AH
    OUT 00H,AL
    ROL AH,1
    PUSH CX
    MOV CX,700H
    LOOP $
    POP CX    
    INC SI
    LOOP WAITE   
    INC BX
    CMP BX,24
    JA RESET
CONTINUE:    
    JMP RUN
RESET:
    MOV BX,00H
    JMP CONTINUE
CODE ENDS
END START
